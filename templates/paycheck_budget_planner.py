"""Paycheck Budget Planner – budget by paycheck (weekly, biweekly, twice a month or monthly). Sample + blank versions.

Settings (pay frequency, first payday, take-home pay, savings per paycheck) -> Paychecks (every payday for 12 months,
generated by formulas) -> Bills (monthly, every-paycheck and yearly bills with due day) -> Bill Schedule (which paycheck
pays which bill: a bill belongs to the paycheck whose pay period contains its due date) -> Spending log ->
Dashboard (next paycheck and the bills it must cover, month-by-month view, extra-paycheck months, categories, chart).
"""
import datetime as dt
from openpyxl import Workbook
from openpyxl.styles import Font, Alignment
from openpyxl.worksheet.datavalidation import DataValidation
from openpyxl.formatting.rule import FormulaRule, CellIsRule
from openpyxl.chart import BarChart, Reference
from openpyxl.utils import get_column_letter as L
from _common import Kit, F, INK, B, MONEY, DATE, font, fill, style_range, input_cell, finish

MAIN = "0E7490"; SOFT = "E6F6FA"
K = Kit(MAIN, SOFT)
NP = 53                      # paychecks (weekly = 52-53 per year)
P0 = 5; P1 = P0 + NP - 1     # Paychecks rows 5..57
NB = 40                      # bills
B0 = 5; B1 = B0 + NB - 1     # Bills rows 5..44 (same rows on Bill Schedule)
NS = 400                     # spending rows
S0 = 5; S1 = S0 + NS - 1
NC = 16                      # categories
PCOL = [L(5 + k) for k in range(NP)]     # Bill Schedule paycheck columns E..BE
NXT = L(5 + NP + 1)          # BG  amount due from next paycheck
RNK = L(5 + NP + 2)          # BH  rank among bills due next paycheck
FREQS = ["Weekly", "Every 2 weeks (biweekly)", "Twice a month (15th & last day)", "Monthly"]
BFREQ = ["Monthly", "Every paycheck", "Yearly"]
CATS = ["Housing", "Utilities", "Food & groceries", "Transport", "Insurance", "Debt payments", "Subscriptions", "Health",
        "Personal care", "Entertainment", "Shopping", "Dining out", "Kids", "Pets", "Gifts & giving", "Other"]
MON = 'mmm yyyy'
ST, FQ, PAY, SAV, TYP, ASOF = ("Settings!$B$6", "Settings!$B$11", "Settings!$B$7", "Settings!$B$8", "Settings!$B$12", "Settings!$B$9")
BS = "'Bill Schedule'"


def build(sample, path):
    wb = Workbook()
    st = wb.active; st.title = "Start Here"
    dash = wb.create_sheet("Dashboard"); pc = wb.create_sheet("Paychecks"); bl = wb.create_sheet("Bills")
    bs = wb.create_sheet("Bill Schedule"); sp = wb.create_sheet("Spending"); s = wb.create_sheet("Settings")

    # ---------- Settings ----------
    K.title(s, "Settings", "Yellow cells are yours to edit.")
    rows = [("Currency label", "USD", None),
            ("Pay frequency", FREQS[1], None),
            ("First payday of the plan", dt.date(2027, 1, 1) if sample else "=TODAY()-WEEKDAY(TODAY(),2)+12", DATE),
            ("Take-home pay per paycheck", 2400 if sample else None, MONEY),
            ("Save from every paycheck", 150 if sample else None, MONEY),
            ("Today / as-of date", dt.date(2027, 2, 10) if sample else "=TODAY()", DATE)]
    for i, (k_, v, fmt) in enumerate(rows, 4):
        s.cell(row=i, column=1, value=k_).font = font(bold=True)
        c = s.cell(row=i, column=2); input_cell(c, v)
        if fmt: c.number_format = fmt
    notes = {5: "Choose from the list.", 6: "Type the date of your first paycheck. The plan covers the 12 months from this date.",
             7: "Your usual net pay (after tax). Change single paychecks on the Paychecks tab.",
             8: "Moved to savings from every paycheck (emergency fund, goals).", 9: "Leave as =TODAY() – used to find your next paycheck."}
    for r, t in notes.items(): s[f"C{r}"] = t; s[f"C{r}"].font = font(italic=True, size=9)
    calc = [("Frequency number (1-4)", "=IFERROR(MATCH(B5,$H$5:$H$8,0),2)", "0"),
            ("Usual paychecks per month", "=CHOOSE(B11,4,2,2,1)", "0"),
            ("Plan ends (last day)", "=EDATE(B6,12)-1", DATE)]
    for i, (k_, f, fmt) in enumerate(calc, 11):
        s.cell(row=i, column=1, value=k_).font = font(italic=True)
        c = s.cell(row=i, column=2, value=f); c.number_format = fmt; c.border = B; c.fill = fill("F3F4F6"); c.font = font()
    s["H4"] = "Pay frequencies"; s["J4"] = "Categories (edit the names if you like)"; s["L4"] = "Bill frequencies"
    for a in ("H4", "J4", "L4"): s[a].font = font(bold=True, size=9)
    for i, f in enumerate(FREQS): s.cell(row=5 + i, column=8, value=f).font = font(size=9)
    for i, c in enumerate(CATS): input_cell(s.cell(row=5 + i, column=10), c)
    for i, f in enumerate(BFREQ): s.cell(row=5 + i, column=12, value=f).font = font(size=9)
    dv = DataValidation(type="list", formula1="=$H$5:$H$8", allow_blank=False); s.add_data_validation(dv); dv.add("B5")
    for c, w in zip("ABCDEFGHIJKL", [30, 16, 70, 3, 3, 3, 3, 30, 3, 24, 3, 16]): s.column_dimensions[c].width = w

    # ---------- Paychecks ----------
    K.title(pc, "Paychecks", "Every payday for 12 months, calculated from the Settings tab. Type a different amount in the yellow column if one paycheck is different.")
    heads = ["#", "Pay date", "Pay period ends", "Month", "Expected take-home", "Actual take-home (optional)", "Take-home used",
             "Bills due", "Savings", "Left to spend", "Spent (Spending tab)", "Remaining", "Paychecks in this month",
             "Raw date", "Next raw date", "Extra paycheck"]
    K.hdr(pc, 4, heads, [6, 12, 13, 11, 14, 15, 14, 13, 12, 14, 14, 13, 12, 11, 11, 10])
    style_range(pc, P0, P1, 1, 16, inputs=(6,), fmt={2: DATE, 3: DATE, 4: MON, 5: MONEY, 6: MONEY, 7: MONEY, 8: MONEY,
                                                    9: MONEY, 10: MONEY, 11: MONEY, 12: MONEY, 14: DATE, 15: DATE})

    def raw(n):
        return (f"CHOOSE({FQ},{ST}+7*({n}-1),{ST}+14*({n}-1),"
                f"IF(MOD({n}-1+IF(DAY({ST})<=15,0,1),2)=0,DATE(YEAR({ST}),MONTH({ST})+({n}-1+IF(DAY({ST})<=15,0,1))/2,15),"
                f"EOMONTH({ST},({n}-2+IF(DAY({ST})<=15,0,1))/2)),EDATE({ST},{n}-1))")
    for i in range(NP):
        r = P0 + i
        pc[f"A{r}"] = i + 1
        pc[f"N{r}"] = "=" + raw(f"A{r}")
        pc[f"O{r}"] = "=" + raw(f"(A{r}+1)")
        pc[f"B{r}"] = f'=IF(N{r}<=Settings!$B$13,N{r},"")'
        pc[f"C{r}"] = f'=IF(B{r}="","",O{r}-1)'
        pc[f"D{r}"] = f'=IF(B{r}="","",B{r})'
        pc[f"E{r}"] = f'=IF(B{r}="","",N({PAY}))'
        pc[f"G{r}"] = f'=IF(B{r}="","",IF(F{r}="",E{r},N(F{r})))'
        pc[f"H{r}"] = f'=IF(B{r}="","",{BS}!{PCOL[i]}${B1 + 1})'
        pc[f"I{r}"] = f'=IF(B{r}="","",N({SAV}))'
        pc[f"J{r}"] = f'=IF(B{r}="","",G{r}-H{r}-I{r})'
        pc[f"K{r}"] = f'=IF(B{r}="","",SUMIFS(Spending!$D${S0}:$D${S1},Spending!$A${S0}:$A${S1},">="&B{r},Spending!$A${S0}:$A${S1},"<="&C{r}))'
        pc[f"L{r}"] = f'=IF(B{r}="","",J{r}-K{r})'
        pc[f"M{r}"] = f'=IF(B{r}="","",COUNTIFS($B${P0}:$B${P1},">="&DATE(YEAR(B{r}),MONTH(B{r}),1),$B${P0}:$B${P1},"<="&EOMONTH(B{r},0)))'
        pc[f"P{r}"] = f'=IF(B{r}="",0,IF(COUNTIFS($B${P0}:B{r},">="&DATE(YEAR(B{r}),MONTH(B{r}),1))>{TYP},1,0))'
    pc[f"A{P1 + 1}"] = "Total"
    for c in "GHIJKL": pc[f"{c}{P1 + 1}"] = f"=SUM({c}{P0}:{c}{P1})"
    pc[f"P{P1 + 1}"] = f"=SUM(P{P0}:P{P1})"
    for c in "AGHIJKLP":
        x = pc[f"{c}{P1 + 1}"]; x.font = font(bold=True); x.border = B; x.fill = fill(SOFT)
        if c not in "AP": x.number_format = MONEY
    pc.conditional_formatting.add(f"A{P0}:M{P1}", FormulaRule(formula=[f"$P{P0}=1"], fill=fill("FEF3C7"), font=Font(name=F, bold=True, color="92400E")))
    pc.conditional_formatting.add(f"L{P0}:L{P1}", CellIsRule(operator="lessThan", formula=["0"], font=Font(name=F, bold=True, color="B91C1C")))
    pc.conditional_formatting.add(f"J{P0}:J{P1}", CellIsRule(operator="lessThan", formula=["0"], font=Font(name=F, bold=True, color="B91C1C")))
    pc[f"A{P1 + 3}"] = ("Yellow rows = extra paychecks (a 3rd paycheck in a month on biweekly pay, or a 5th on weekly pay) – "
                        "your bills are already covered that month, so this money can go to savings or debt.")
    pc[f"A{P1 + 3}"].font = font(italic=True, size=9)
    pc.column_dimensions["N"].hidden = False
    pc.freeze_panes = "C5"

    # ---------- Bills ----------
    K.title(bl, "Bills", "One row per bill or regular cost. 'Every paycheck' = an amount you set aside from each paycheck (groceries, gas).")
    heads = ["Bill", "Category", "Amount", "How often", "Due day (1-31)", "Due month (yearly bills, 1-12)", "Autopay?",
             "Cost in plan (12 months)", "Clean due day", "Clean due month", "Check"]
    K.hdr(bl, 4, heads, [26, 18, 12, 16, 10, 12, 10, 14, 9, 9, 34])
    style_range(bl, B0, B1, 1, 11, inputs=(1, 2, 3, 4, 5, 6, 7), fmt={3: MONEY, 8: MONEY})
    if sample:
        data = [("Rent", "Housing", 1400, "Monthly", 1, None, "No"), ("Electricity", "Utilities", 95, "Monthly", 18, None, "Yes"),
                ("Internet", "Utilities", 60, "Monthly", 22, None, "Yes"), ("Phone", "Utilities", 45, "Monthly", 12, None, "Yes"),
                ("Car payment", "Transport", 320, "Monthly", 5, None, "Yes"), ("Car insurance", "Insurance", 110, "Monthly", 25, None, "Yes"),
                ("Student loan", "Debt payments", 210, "Monthly", 15, None, "Yes"), ("Credit card", "Debt payments", 150, "Monthly", 28, None, "No"),
                ("Streaming", "Subscriptions", 15.49, "Monthly", 9, None, "Yes"), ("Gym", "Health", 30, "Monthly", 3, None, "Yes"),
                ("Groceries", "Food & groceries", 220, "Every paycheck", None, None, "No"), ("Gas", "Transport", 70, "Every paycheck", None, None, "No"),
                ("Online shopping membership", "Subscriptions", 139, "Yearly", 14, 3, "Yes"), ("Car registration", "Transport", 95, "Yearly", 1, 7, "No"),
                ("Renters insurance", "Insurance", 180, "Yearly", 10, 9, "Yes")]
        for i, row in enumerate(data):
            for j, v in enumerate(row, 1):
                if v is not None: bl.cell(row=B0 + i, column=j, value=v)
    for r in range(B0, B1 + 1):
        bl[f"H{r}"] = (f'=IF(OR(A{r}="",N(C{r})=0),"",IF(D{r}="Monthly",C{r}*12,IF(D{r}="Every paycheck",C{r}*COUNT(Paychecks!$B${P0}:$B${P1}),'
                       f'IF(D{r}="Yearly",C{r},0))))')
        bl[f"I{r}"] = f"=MIN(31,MAX(1,INT(N(E{r}))))"
        bl[f"J{r}"] = f"=MIN(12,MAX(1,INT(N(F{r}))))"
        bl[f"K{r}"] = (f'=IF(A{r}="","",IF(N(C{r})=0,"Add the amount",IF(D{r}="","Choose how often",'
                       f'IF(AND(D{r}<>"Every paycheck",N(E{r})=0),"Add the due day",IF(AND(D{r}="Yearly",N(F{r})=0),"Add the due month","OK")))))')
    bl[f"A{B1 + 1}"] = "Total per year"; bl[f"H{B1 + 1}"] = f"=SUM(H{B0}:H{B1})"
    for c in "AH":
        x = bl[f"{c}{B1 + 1}"]; x.font = font(bold=True); x.border = B; x.fill = fill(SOFT)
    bl[f"H{B1 + 1}"].number_format = MONEY
    for ref, f1 in (("B5:B44", f"=Settings!$J$5:$J${4 + NC}"), ("D5:D44", "=Settings!$L$5:$L$7"), ("G5:G44", '"Yes,No"')):
        dv = DataValidation(type="list", formula1=f1, allow_blank=True); bl.add_data_validation(dv); dv.add(ref)
    bl.conditional_formatting.add(f"K{B0}:K{B1}", FormulaRule(formula=[f'AND(K{B0}<>"",K{B0}<>"OK")'], fill=fill("FEE2E2"), font=Font(name=F, bold=True, color="B91C1C")))
    bl.conditional_formatting.add(f"K{B0}:K{B1}", CellIsRule(operator="equal", formula=['"OK"'], fill=fill("D1FAE5")))
    bl[f"A{B1 + 3}"] = "A bill is paid from the paycheck whose pay period includes its due date. Due day 31 means the last day of shorter months."
    bl[f"A{B1 + 3}"].font = font(italic=True, size=9)
    bl.freeze_panes = "B5"

    # ---------- Bill Schedule ----------
    K.title(bs, "Bill Schedule", "Which paycheck pays which bill. Calculated – nothing to type.")
    bs["A3"] = "Pay date"; bs["A4"] = "Pay period ends"
    for a in ("A3", "A4"): bs[a].font = font(bold=True, size=9)
    K.hdr(bs, 2, ["", "", "", ""] + [f"Paycheck {k + 1}" for k in range(NP)], [26, 11, 14, 8] + [11] * NP)
    bs["A2"] = "Bill"; bs["B2"] = "Amount"; bs["C2"] = "How often"; bs["D2"] = "Due day"
    for k, c in enumerate(PCOL):
        bs[f"{c}3"] = f'=Paychecks!B{P0 + k}'; bs[f"{c}4"] = f'=Paychecks!C{P0 + k}'
        for rr in (3, 4): bs[f"{c}{rr}"].number_format = 'mmm d'; bs[f"{c}{rr}"].font = font(bold=True, size=9)
    # rows B0..B1 mirror Bills rows (header block sits in rows 2-4)
    for r in range(B0, B1 + 1):
        bs[f"A{r}"] = f'=IF(Bills!A{r}="","",Bills!A{r})'
        bs[f"B{r}"] = f'=N(Bills!C{r})'
        bs[f"C{r}"] = f'=IF(Bills!D{r}="","",Bills!D{r})'
        bs[f"D{r}"] = f'=IF(C{r}="Every paycheck","",Bills!I{r})'
        for c in PCOL:
            S = f"{c}$3"; E = f"{c}$4"; D = f"Bills!$I{r}"; M = f"Bills!$J{r}"
            d1 = f"DATE(YEAR({S}),MONTH({S}),MIN({D},DAY(EOMONTH({S},0))))"
            d2 = f"DATE(YEAR({S}),MONTH({S})+1,MIN({D},DAY(EOMONTH({S},1))))"
            y1 = f"DATE(YEAR({S}),{M},MIN({D},DAY(EOMONTH(DATE(YEAR({S}),{M},1),0))))"
            y2 = f"DATE(YEAR({S})+1,{M},MIN({D},DAY(EOMONTH(DATE(YEAR({S})+1,{M},1),0))))"
            bs[f"{c}{r}"] = (f'=IF(OR({S}="",$A{r}=""),0,IF($C{r}="Every paycheck",$B{r},IF($C{r}="Monthly",'
                             f'$B{r}*(({d1}>={S})*({d1}<={E})+({d2}>={S})*({d2}<={E})),IF($C{r}="Yearly",'
                             f'$B{r}*(({y1}>={S})*({y1}<={E})+({y2}>={S})*({y2}<={E})),0))))')
        bs[f"{NXT}{r}"] = f"=IF(Dashboard!$L$1>{NP},0,INDEX(${PCOL[0]}{r}:${PCOL[-1]}{r},1,Dashboard!$L$1))"
        bs[f"{RNK}{r}"] = f'=IF({NXT}{r}>0,COUNTIF(${NXT}${B0}:{NXT}{r},">0"),"")'
    tr = B1 + 1
    bs[f"A{tr}"] = "Total bills"
    for c in ["B"] + PCOL + [NXT]: bs[f"{c}{tr}"] = f"=SUM({c}{B0}:{c}{B1})"
    bs[f"{NXT}2"] = "Next paycheck"; bs[f"{RNK}2"] = "Order"
    for a in (f"{NXT}2", f"{RNK}2"):
        bs[a].font = Font(name=F, bold=True, color="FFFFFF"); bs[a].fill = fill(MAIN); bs[a].alignment = Alignment(wrap_text=True)
    bs.column_dimensions[NXT].width = 12; bs.column_dimensions[RNK].width = 8
    fmt = {2: MONEY}
    for k in range(NP): fmt[5 + k] = MONEY
    style_range(bs, B0, tr, 1, 4 + NP, fmt=fmt)
    style_range(bs, B0, tr, 5 + NP + 1, 5 + NP + 2, fmt={5 + NP + 1: MONEY})
    for c in ["A", "B"] + PCOL + [NXT]:
        bs[f"{c}{tr}"].font = font(bold=True); bs[f"{c}{tr}"].fill = fill(SOFT)
    bs.conditional_formatting.add(f"{PCOL[0]}{B0}:{PCOL[-1]}{B1}", CellIsRule(operator="greaterThan", formula=["0"], fill=fill("CFFAFE"), font=Font(name=F, bold=True, color="155E75")))
    bs.freeze_panes = "E5"

    # ---------- Spending ----------
    K.title(sp, "Spending", "Log day-to-day spending that is not a bill. It is matched to the paycheck it came from.")
    K.hdr(sp, 4, ["Date", "Description", "Category", "Amount", "Paycheck #"], [12, 30, 20, 12, 12])
    style_range(sp, S0, S1, 1, 5, inputs=(1, 2, 3, 4), fmt={1: DATE, 4: MONEY})
    if sample:
        log = [(1, 3, "Coffee & bagel", "Dining out", 9.80), (1, 6, "Movie tickets", "Entertainment", 28), (1, 9, "Pharmacy", "Health", 18.45),
               (1, 14, "Pizza night", "Dining out", 32.5), (1, 17, "Haircut", "Personal care", 35),
               (1, 20, "Birthday gift", "Gifts & giving", 40), (1, 23, "Dog food", "Pets", 46.2), (1, 26, "Concert", "Entertainment", 75),
               (1, 29, "Lunch with friends", "Dining out", 24.6), (2, 1, "Books", "Shopping", 22.9), (2, 4, "Takeout", "Dining out", 27.3),
               (2, 7, "Cinema", "Entertainment", 16), (2, 9, "Cleaning supplies", "Other", 19.75), (2, 13, "Valentine's dinner", "Dining out", 88),
               (2, 16, "Vet check-up", "Pets", 65), (2, 19, "T-shirts", "Shopping", 38), (2, 22, "Bowling", "Entertainment", 30)]
        for i, (m, d, desc, cat, amt) in enumerate(log):
            r = S0 + i
            sp[f"A{r}"] = dt.date(2027, m, d); sp[f"B{r}"] = desc; sp[f"C{r}"] = cat; sp[f"D{r}"] = amt
    for r in range(S0, S1 + 1):
        sp[f"E{r}"] = (f'=IF(A{r}="","",IF(COUNTIF(Paychecks!$B${P0}:$B${P1},"<="&A{r})=0,"Before plan",'
                       f'IF(A{r}>Settings!$B$13,"After plan",COUNTIF(Paychecks!$B${P0}:$B${P1},"<="&A{r}))))')
        sp[f"E{r}"].alignment = Alignment(horizontal="center")
    dv = DataValidation(type="list", formula1=f"=Settings!$J$5:$J${4 + NC}", allow_blank=True); sp.add_data_validation(dv); dv.add(f"C{S0}:C{S1}")
    sp.freeze_panes = "A5"

    # ---------- Dashboard ----------
    K.title(dash, "Paycheck Budget Dashboard", "Updates by itself. Set your pay on the Settings tab and add your bills on the Bills tab.")
    dash["A3"] = '="Paid: "&Settings!B5&"  ·  Plan: "&TEXT(Settings!B6,"mmm d, yyyy")&" – "&TEXT(Settings!B13,"mmm d, yyyy")&"  ·  Amounts in "&Settings!B4'
    dash["A3"].font = font(bold=True)
    dash["L1"] = f'=MIN({NP + 1},COUNTIF(Paychecks!$B${P0}:$B${P1},"<"&INT({ASOF}))+1)'
    dash["L1"].font = Font(name=F, size=8, color="FFFFFF")
    PT = P1 + 1
    kp = [("Paychecks in your plan", f"=COUNT(Paychecks!B{P0}:B{P1})", "0"),
          ("Take-home pay (12 months)", f"=Paychecks!G{PT}", MONEY),
          ("Bills (12 months)", f"=Paychecks!H{PT}", MONEY),
          ("Savings (12 months)", f"=Paychecks!I{PT}", MONEY),
          ("Left to spend per paycheck (avg)", f'=IFERROR(Paychecks!J{PT}/A6,0)', MONEY),
          ("Extra paychecks", f"=Paychecks!P{PT}", "0")]
    for i, (lab, f, fmt) in enumerate(kp):
        K.kpi(dash, 5 + (i // 3) * 3, 1 + (i % 3) * 2, lab, f, fmt)
    for c, w in zip("ABCDEFGH", [26, 15, 22, 15, 22, 15, 13, 13]): dash.column_dimensions[c].width = w

    K.section(dash, "A11", "Next paycheck")
    nx = "$L$1"
    def pick(col): return f'=IF({nx}>COUNT(Paychecks!$B${P0}:$B${P1}),"",INDEX(Paychecks!${col}${P0}:${col}${P1},{nx}))'
    nrows = [("Paycheck #", f'=IF({nx}>COUNT(Paychecks!$B${P0}:$B${P1}),"Plan finished",{nx})', "0"),
             ("Pay date", pick("B"), "mmm d, yyyy"), ("Pay period ends", pick("C"), "mmm d, yyyy"), ("Take-home pay", pick("G"), MONEY),
             ("Bills to pay", pick("H"), MONEY), ("Savings", pick("I"), MONEY), ("Left to spend", pick("J"), MONEY)]
    for i, (lab, f, fmt) in enumerate(nrows, 13):
        dash[f"A{i}"] = lab; dash[f"A{i}"].font = font(bold=True); dash[f"A{i}"].border = B; dash[f"A{i}"].fill = fill(SOFT)
        c = dash[f"B{i}"]; c.value = f; c.number_format = fmt; c.border = B; c.font = Font(name=F, bold=True, color=MAIN)
        c.alignment = Alignment(horizontal="right")
    K.section(dash, "C11", "Bills to pay from the next paycheck")
    K.hdr(dash, 12, ["Bill", "Due day", "Amount"], col0=3)
    for k in range(10):
        r = 13 + k; m = f"MATCH({k + 1},{BS}!${RNK}${B0}:${RNK}${B1},0)"
        dash[f"C{r}"] = f'=IFERROR(INDEX({BS}!$A${B0}:$A${B1},{m}),"")'
        dash[f"D{r}"] = f'=IFERROR(IF(INDEX({BS}!$D${B0}:$D${B1},{m})="","each paycheck",INDEX({BS}!$D${B0}:$D${B1},{m})),"")'
        dash[f"E{r}"] = f'=IFERROR(INDEX({BS}!${NXT}${B0}:${NXT}${B1},{m}),"")'
    style_range(dash, 13, 22, 3, 5, fmt={5: MONEY})
    for r in range(13, 23): dash[f"D{r}"].alignment = Alignment(horizontal="center")
    dash["C23"] = f'=IF(COUNTIF({BS}!${RNK}${B0}:${RNK}${B1},">10")>0,"+ "&COUNTIF({BS}!${RNK}${B0}:${RNK}${B1},">10")&" more on the Bill Schedule tab","")'
    dash["C23"].font = font(italic=True, size=9)

    K.section(dash, "A25", "Month by month")
    K.hdr(dash, 26, ["Month", "Paychecks", "Take-home pay", "Bills", "Savings", "Left to spend", "Spent", "Remaining"])
